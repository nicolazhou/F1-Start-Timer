  const languages = Object.freeze(Object.keys(messages));
  function baseLanguage(value) {
    if (typeof value !== "string") return "";
    const base = value.trim().toLowerCase().split(/[-_]/, 1)[0];
    return languages.includes(base) ? base : "";
  }
  function resolveLanguage(preference = "auto", browserLanguages = []) {
    if (preference !== "auto") return baseLanguage(preference) || "en";
    for (const value of Array.isArray(browserLanguages) ? browserLanguages : [browserLanguages]) {
      const candidate = baseLanguage(value);
      if (candidate) return candidate;
    }
    return "en";
  }
  function translate(language, key, params = {}) {
    const template = (messages[language] || messages.en)[key] ?? messages.en[key];
    if (template === undefined) throw new Error(`Missing translation: ${key}`);
    return template.replace(/\{(\w+)\}/g, (match, name) =>
      Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match);
  }
